// Draws the Qubrynt logo: a "Q" folded out of paper, in deep green and cream on charcoal.
// Run:  node scripts/make-logo.mjs   (writes src/components/logoShapes.ts and public/logo.svg + favicon.svg)
import fs from 'node:fs'

const BG = '#262626'
const PALETTE = ['#0b3d2a', '#11593b', '#1a7a50', '#2a9a68', '#e6dcc3', '#f4eddc'] // dark green -> cream
const C = { x: 45, y: 45 }
const N = 12
const R = 33
const r = 17.5

function rng(seed) { // small deterministic random generator so the logo is always identical
  return () => { seed |= 0; seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
}
const rand = rng(11)
const pt = (a, rad) => [C.x + Math.cos(a) * rad, C.y + Math.sin(a) * rad]
const outer = []
const inner = []
for (let i = 0; i < N; i++) {
  const a = (i / N) * Math.PI * 2 + 0.12
  outer.push(pt(a, R + (rand() - 0.5) * 1.8))
  inner.push(pt(a + (rand() - 0.5) * 0.1, r + (rand() - 0.5) * 1.2))
}

// light comes from the top-left: surfaces facing it are cream, surfaces facing away are dark green
const LIGHT = (-3 * Math.PI) / 4
const shade = (tri, bias = 0) => {
  const cx = (tri[0][0] + tri[1][0] + tri[2][0]) / 3
  const cy = (tri[0][1] + tri[1][1] + tri[2][1]) / 3
  const s = Math.cos(Math.atan2(cy - C.y, cx - C.x) - LIGHT)
  const i = s < -0.6 ? 0 : s < -0.2 ? 1 : s < 0.2 ? 2 : s < 0.55 ? 3 : s < 0.8 ? 4 : 5
  return PALETTE[Math.max(0, Math.min(5, i + bias))]
}

const shapes = []
for (let i = 0; i < N; i++) {
  const j = (i + 1) % N
  const t1 = [outer[i], outer[j], inner[j]]
  const t2 = [outer[i], inner[j], inner[i]]
  shapes.push({ tri: t1, fill: shade(t1, 0) })
  shapes.push({ tri: t2, fill: shade(t2, i % 2 ? -1 : 1) })
}

// the tail of the Q: a folded paper strip crossing the ring at the bottom right
const d = [Math.SQRT1_2, Math.SQRT1_2]
const n = [-Math.SQRT1_2, Math.SQRT1_2]
const at = (dist, side) => [C.x + d[0] * dist + n[0] * side, C.y + d[1] * dist + n[1] * side]
const L1 = at(7, 5.4), R1 = at(7, -5.4), Lm = at(33, 4.6), Rm = at(33, -4.6), M = at(33, 0), E = at(51, 0)
shapes.push({ tri: [L1, R1, Rm], fill: PALETTE[4] })
shapes.push({ tri: [L1, Rm, Lm], fill: PALETTE[5] })
shapes.push({ tri: [Lm, M, E], fill: PALETTE[5] })
shapes.push({ tri: [M, Rm, E], fill: PALETTE[3] })

const f = (v) => Math.round(v * 100) / 100
const out = shapes.map(({ tri, fill }) => ({ points: tri.map((p) => `${f(p[0])},${f(p[1])}`).join(' '), fill }))

fs.writeFileSync(new URL('../src/components/logoShapes.ts', import.meta.url), `// Generated by scripts/make-logo.mjs. Do not edit by hand.\nexport const LOGO_BG = '${BG}'\nexport const LOGO_SHAPES: { points: string; fill: string }[] = ${JSON.stringify(out, null, 1)}\n`)
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="Qubrynt"><circle cx="50" cy="50" r="50" fill="${BG}"/>${out.map((s) => `<polygon points="${s.points}" fill="${s.fill}" stroke="${s.fill}" stroke-width="0.3" stroke-linejoin="round"/>`).join('')}</svg>\n`
fs.writeFileSync(new URL('../public/logo.svg', import.meta.url), svg)
fs.writeFileSync(new URL('../public/favicon.svg', import.meta.url), svg)
console.log('logo written,', out.length, 'facets')
